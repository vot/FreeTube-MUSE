/**
 * Name of the route parameter holding the id of the tab a URL belongs to
 */
export const TAB_ID_PARAM = 'tabId'

/**
 * Restricts tab routes to ids generated by the tab system e.g. `tab01`
 */
export const TAB_ID_PATTERN = 'tab\\d+'

/**
 * Prefix that every in-app path gets when the tabbed interface is enabled
 */
export const TAB_PATH_PREFIX = `/:${TAB_ID_PARAM}(${TAB_ID_PATTERN})`

