/**
 * Prepends a tab id segment to every given path, which makes it possible to
 * address the page of an individual tab inside the address bar
 * @param {string} path
 * @returns {string}
 */
function getTabPrefixedPath(path) {
  return path === '/' ? TAB_PATH_PREFIX : `${TAB_PATH_PREFIX}${path}`
}

/**
 * Route names have to be unique, so tab specific routes get a suffix
 * @type {import('vue-router').RouteRecordRaw[]}
 */
export const tabRoutes = baseRoutes.map(route => ({
  ...route,
  path: getTabPrefixedPath(route.path),
  ...(route.name != null ? { name: `${route.name}Tab` } : {})
}))
